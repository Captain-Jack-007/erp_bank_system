export function isLang(v: unknown): v is Lang {
  return v === 'ru' || v === 'uz' || v === 'uzc' || v === 'en';
}

export function translate(lang: Lang, key: TKey): string {
  return (lang === 'uzc' ? uzc() : dictionaries[lang] ?? ruAll)[key] ?? ruAll[key] ?? key;
}

/** Значение данных на языке интерфейса: en → иначе uz; uzc → транслитерация uz. */
export function localize(value: Localized, lang: Lang): string;
export function localize(value: Localized | undefined | null, lang: Lang): string | undefined;
export function localize(value: Localized | undefined | null, lang: Lang): string | undefined {
  if (!value) return undefined;
  switch (lang) {
    case 'ru':
      return value.ru;
    case 'uz':
      return value.uz;
    case 'uzc':
      return toCyrillic(value.uz);
    case 'en':
      return value.en ?? value.uz;
  }
}

/** Строка в коде на нескольких языках: pick(lang, 'Нагрузка', 'Yuklama', 'Workload'). */
export function pick(lang: Lang, ru: string, uz: string, en?: string): string {
  return localize({ ru, uz, en }, lang);
}

