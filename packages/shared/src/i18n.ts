/** Узбекская кириллица: генерируется из латиницы при первом обращении. */
let uzcAll: Record<TKey, string> | null = null;
function uzc(): Record<TKey, string> {
  if (!uzcAll) {
    const out = {} as Record<TKey, string>;
    for (const k of Object.keys(uzAll) as TKey[]) out[k] = toCyrillic(uzAll[k]);
    uzcAll = out;
  }
  return uzcAll;
}

export const dictionaries: Record<Exclude<Lang, 'uzc'>, Record<TKey, string>> & { readonly uzc: Record<TKey, string> } = {
  ru: ruAll,
  uz: uzAll,
  en: enAll,
  get uzc() {
    return uzc();
  },
};

