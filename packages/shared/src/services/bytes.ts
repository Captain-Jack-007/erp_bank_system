// Низкоуровневые утилиты для работы с байтами без зависимостей и без DOM:
// UTF-8, CRC32, SHA-256, Base64. Используются XLSX/ZIP, QR, подписью и файловым сервисом.

/** Строка → байты UTF-8. */
export function utf8Encode(s: string): Uint8Array {
  const out: number[] = [];
  for (let i = 0; i < s.length; i++) {
    let c = s.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdbff && i + 1 < s.length) {
      const d = s.charCodeAt(i + 1);
      if (d >= 0xdc00 && d <= 0xdfff) {
        c = 0x10000 + ((c - 0xd800) << 10) + (d - 0xdc00);
        i++;
      }
    }
    if (c < 0x80) out.push(c);
    else if (c < 0x800) out.push(0xc0 | (c >> 6), 0x80 | (c & 63));
    else if (c < 0x10000) out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    else out.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
  }
  return Uint8Array.from(out);
}

/** Байты UTF-8 → строка (некорректные последовательности заменяются на U+FFFD). */
export function utf8Decode(b: Uint8Array): string {
  let s = '';
  let i = 0;
  const parts: string[] = [];
  while (i < b.length) {
    const c = b[i++]!;
    let cp: number;
    if (c < 0x80) cp = c;
    else if (c >= 0xc0 && c < 0xe0) cp = ((c & 31) << 6) | (b[i++]! & 63);
    else if (c >= 0xe0 && c < 0xf0) cp = ((c & 15) << 12) | ((b[i++]! & 63) << 6) | (b[i++]! & 63);
    else if (c >= 0xf0) cp = ((c & 7) << 18) | ((b[i++]! & 63) << 12) | ((b[i++]! & 63) << 6) | (b[i++]! & 63);
    else cp = 0xfffd;
    s += String.fromCodePoint(cp);
    if (s.length > 8192) {
      parts.push(s);
      s = '';
    }
  }
  parts.push(s);
  return parts.join('');
}

let crcTable: Uint32Array | null = null;
/** CRC-32 (IEEE 802.3), как в ZIP. */
export function crc32(data: Uint8Array): number {
  if (!crcTable) {
    crcTable = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      crcTable[n] = c >>> 0;
    }
  }
  let crc = 0xffffffff;
  for (let i = 0; i < data.length; i++) crc = crcTable[(crc ^ data[i]!) & 0xff]! ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

